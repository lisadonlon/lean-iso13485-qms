/*
Harvest the repository's QMS content into src/generated/templates.ts.

Runs as a build prestep (npm run harvest). The repository's markdown documents
remain the single source of truth; this script bundles them into the plugin so
a fresh vault can be scaffolded offline. The generated file is gitignored.
*/
import { execSync } from "child_process";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath } from "url";

const PLUGIN_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = resolve(PLUGIN_ROOT, "..");

// Folders whose markdown content is bundled as scaffold templates.
const CONTENT_FOLDERS = [
  "00-dashboard",
  "01-quality-manual",
  "02-procedures",
  "03-work-instructions",
  "04-forms-templates",
  "06-isms",
  "07-process-maps",
  "08-references",
  "_templates",
];

// Records tree: only the README is bundled; subfolders are created empty.
const RECORDS_FOLDER = "05-records";
const RECORD_SUBDIRS = [
  "audits",
  "capa",
  "changes",
  "complaints",
  "distribution",
  "management-reviews",
  "software-validation",
  "training",
];

// Baseline Obsidian config written into a fresh vault if absent.
const OBSIDIAN_CONFIG_FILES = [
  ".obsidian/app.json",
  ".obsidian/appearance.json",
  ".obsidian/community-plugins.json",
  ".obsidian/core-plugins.json",
];

function docIdFromContent(content) {
  const m = content.match(/^doc_id:\s*(\S+)\s*$/m);
  return m ? m[1] : null;
}

function collectMarkdown(folder) {
  const abs = join(REPO_ROOT, folder);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const name of readdirSync(abs).sort()) {
    const p = join(abs, name);
    if (statSync(p).isDirectory()) continue;
    if (!name.endsWith(".md")) continue;
    const content = readFileSync(p, "utf-8");
    out.push({ path: `${folder}/${name}`, docId: docIdFromContent(content), content });
  }
  return out;
}

const docs = [];
for (const folder of CONTENT_FOLDERS) {
  docs.push(...collectMarkdown(folder));
}
const recordsReadme = join(REPO_ROOT, RECORDS_FOLDER, "README.md");
if (existsSync(recordsReadme)) {
  docs.push({
    path: `${RECORDS_FOLDER}/README.md`,
    docId: null,
    content: readFileSync(recordsReadme, "utf-8"),
  });
}

const configFiles = [];
for (const rel of OBSIDIAN_CONFIG_FILES) {
  const abs = join(REPO_ROOT, rel);
  if (existsSync(abs)) {
    configFiles.push({ path: rel, content: readFileSync(abs, "utf-8") });
  }
}

let commit = "unknown";
try {
  commit = execSync("git rev-parse --short HEAD", { cwd: REPO_ROOT }).toString().trim();
} catch {
  // not a git checkout; leave as unknown
}

const folders = [...CONTENT_FOLDERS.filter((f) => f !== "_templates"), RECORDS_FOLDER, "_templates", "_archive"];

const header = `// GENERATED by plugin/scripts/harvest-templates.mjs - do not edit.
// Source commit: ${commit}
`;

const body = `${header}
export interface BundledDoc {
  path: string;
  docId: string | null;
  content: string;
}

export interface BundledConfigFile {
  path: string;
  content: string;
}

export const HARVEST_COMMIT = ${JSON.stringify(commit)};

export const VAULT_FOLDERS: string[] = ${JSON.stringify(folders, null, 2)};

export const RECORD_SUBDIRS: string[] = ${JSON.stringify(RECORD_SUBDIRS, null, 2)};

export const BUNDLED_CONFIG_FILES: BundledConfigFile[] = ${JSON.stringify(configFiles, null, 2)};

export const BUNDLED_DOCS: BundledDoc[] = ${JSON.stringify(docs, null, 2)};
`;

const outDir = join(PLUGIN_ROOT, "src", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "templates.ts"), body, "utf-8");

console.log(`Harvested ${docs.length} documents and ${configFiles.length} config files at ${commit}.`);
